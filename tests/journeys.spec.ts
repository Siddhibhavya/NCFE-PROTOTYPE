import {test,expect} from '@playwright/test';
import {fillProgramme,openApp} from './audit-helpers';
test.beforeEach(async({page})=>page.setViewportSize({width:407,height:884}));
for(const id of ['fetp','mssp','fepa','fact','nflat','elms'])test(`${id}: own form, validation, cancel, submit overlay and return`,async({page})=>{
 await openApp(page,`initiatives/${id}`);
 const request=page.getByRole('link',{name:id==='elms'?'Register':'Request for programme',exact:true});
 const position=await request.boundingBox();
 await page.locator('main').evaluate(el=>el.scrollTo({top:el.scrollHeight,behavior:'instant'}));
 expect(await request.boundingBox()).toEqual(position);
 await request.click();
 expect(page.url()).toContain(`/${id}/register`);
 await page.getByRole('button',{name:'Go back'}).click();
 expect(page.url().split('#')[1]).toBe(`/initiatives/${id}`);
 await page.getByRole('link',{name:id==='elms'?'Register':'Request for programme',exact:true}).click();
 const first=page.locator('form input').first();
 await page.getByRole('button',{name:'Submit',exact:true}).click();
 await expect(first).toHaveAttribute('aria-invalid','true');
 await expect(first).toBeFocused();
 await fillProgramme(page);
 await expect(first).toHaveCSS('background-color','rgb(255, 255, 255)');
 const value=await first.inputValue();
 await page.getByRole('button',{name:'Submit',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 expect((await page.getByRole('dialog').boundingBox())!.y).toBeCloseTo(376,0);
 await page.screenshot({animations:'disabled',path:`docs/screenshots/audit-${id}-confirmation.png`});
 expect(page.url()).toContain('/register');
 await expect(page.locator('form')).toBeVisible();
 await page.getByRole('button',{name:'No',exact:true}).click();
 await expect(first).toHaveValue(value);
 const submit=page.getByRole('button',{name:'Submit',exact:true});
 await submit.scrollIntoViewIfNeeded();
 const bounds=await submit.boundingBox();
 const nav=await page.getByRole('navigation').boundingBox();
 expect(bounds!.y+bounds!.height).toBeLessThanOrEqual(nav!.y-12);
 await submit.hover();
 await expect(submit).toHaveCSS('background-color','rgb(219, 41, 48)');
 await submit.click();
 await page.getByRole('button',{name:'Yes',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Form submitted',exact:true})).toBeVisible();
 await expect(page.getByRole('dialog')).toContainText('in this prototype');
 await expect(page.locator('form')).toBeVisible();
 await page.screenshot({animations:'disabled',path:`docs/screenshots/audit-${id}-submitted.png`});
 await page.getByRole('button',{name:'Done',exact:true}).click();
 expect(page.url().split('#')[1]).toBe(`/initiatives/${id}`);
 await page.getByRole('link',{name:id==='elms'?'Register':'Request for programme',exact:true}).click();
 await expect(page.locator('form input').first()).toHaveValue('');
});
